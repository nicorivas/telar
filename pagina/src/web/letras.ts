/** El texto en letras grandes: cinco líneas, una letra al lado de la otra con un espacio entre ellas. */
export function grande(texto: string): string[] {
    const letras = [...texto.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase()].map(c => FUENTE[c] ?? FUENTE[' ']);
    return [0, 1, 2, 3, 4].map(fila => letras.map(l => l[fila].replace(/#/g, '█').replace(/\./g, ' ')).join(' '));
}
